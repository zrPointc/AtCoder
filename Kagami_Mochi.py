"""
入力の意味：
N個の餅の直径が与えられる。

やること：
異なる直径が何種類あるか数える。

使うデータ：
- 直径を入れる集合（set）
  → 同じ直径が複数あっても、1個だけ残せる
- 入力された直径 d
  → 1個ずつ集合に追加するために使う

計算量：
O(N log N)
（N個の値をsetに追加するため）

注意する境界条件：
- 全部同じ直径なら答えは1
- 全部異なる直径なら答えはN
"""

n = int(input())

values = set()
for _ in range(n):
    values.add(int(input()))

print(len(values))


