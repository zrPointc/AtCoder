a, b = map(int, input().split())
answer = 0
for i in range(a, b+1):
    l = []
    for j in range(5):
        l.append(str(i)[j])
    if l[0] == l[4] and l[1] == l[3]:
        answer += 1
print(answer)

# =================================================================
# 【メモ：回文数の判定方法（スライス）】
# 
# ・数値を文字列に変換し「 s == s[::-1] 」で比較すると簡単に回文判定ができる。
# ・Pythonの「 [::-1] 」は、文字列を後ろから逆順（反転）にするスライス機能。
# ・元の文字列と反転させた文字列が一致すれば、前から読んでも後ろから読んでも同じ（回文）。
# ・この方法は、問題の桁数（5桁など）が変わってもそのまま使えるので汎用性が高い。
