# ・税抜き価格 X を「1円」から順番に1つずつ試していく（全探索）。
# ・問題の制約で税額 A, B は最大100なので、X が1100以上になることは絶対にない。
#   （1100円の10%は110円となり、Bの最大100を超えるため）
# ・そのため、ループの範囲は 1 〜 1099 まで（range(1, 1100)）調べれば確実に網羅できる。
# ・条件に合う X が見つかったら、それが最小の値なので、出力して即終了（exit()）する。
# ・1099まで試しても見つからなかった場合は、ループ外で「-1」を出力する。
